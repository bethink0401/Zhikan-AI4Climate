"""V9.3 Experiment: innovation-1 synthetic known-source world.

The strongest automation-only check of source attribution: build a FULLY
SYNTHETIC world whose events have KNOWN labels, generated by a mechanism
DIFFERENT from the model's scoring formulas (linear emission superposition +
multiplicative event factors + diurnal cycles), then run the frozen pipeline
and measure attribution accuracy. No human labels involved, no proxy-label
circularity with the rule annotators.

World generator (independent of agent internals):
  - 18 stations (3 roadside + 15 general), 90 days of hourly NO2/NOx;
  - baseline = station level + weekday diurnal traffic cycle + noise;
  - traffic events      : weekday peak, target roadside x1.8 (NOx-rich,
                          NO2/NOx ~0.35), other roadside x1.2;
  - regional events     : ALL stations x1.6 uniformly (aged, ratio ~0.6),
                          any hour;
  - local accumulation  : single station x1.9 at night (00-05h), ratio ~0.5;
  - no-event windows    : label "uncertain";
  - synthetic wind series drives nothing in the generator itself (events are
    imposed exogenously), so the generator cannot "leak" model semantics.

Pipeline adaptations (same for every method, disclosed):
  - tools.air_quality_tools.DEFAULT_DB pointed at the synthetic database
    (real schema), PIT mode ON (baselines precede events);
  - TrafficAgent returns the generator's traffic-pressure signal + noise
    (traffic emissions are part of the synthetic world);
  - MeteorologyAgent returns the synthetic wind summary.

Metrics: per-method accuracy/Macro-F1 vs known labels, per-class recall,
confusion, abstention rate. Attribution is "agreement with known synthetic
ground truth in a linear-superposition world" — one step closer to real
attribution than proxy labels, but still a simulation.

Usage: /usr/bin/python3 tests/benchmarks/v9/governance_synthetic.py
"""
