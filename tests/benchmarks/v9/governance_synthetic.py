def build_world(rng: random.Random) -> dict:
    """生成合成时间序列与事件标签（线性叠加 + 乘性事件因子）。"""
    import datetime as dt

    start = dt.datetime(2024, 6, 1)
    hours = [start + dt.timedelta(hours=h) for h in range(N_DAYS * 24)]
    # 事件排布：第 30 天起，每类 15 个，同类间隔 ≥4 天，互不重叠
    events = []
    day_cursor = {0: 30, 1: 33, 2: 36, 3: 39}   # 0=traffic 1=regional 2=local 3=none
    classes = [("traffic_dominant", 0), ("regional_transport", 1),
               ("local_accumulation", 2), ("uncertain", 3)]
    for label, slot in classes:
        day = day_cursor[slot]
        for k in range(N_EVENTS_PER_CLASS):
            events.append({"label": label, "date": (start + dt.timedelta(days=day)).date(),
                           "start_hour": rng.choice([7, 8, 18, 19] if label ==
                                                    "traffic_dominant" else
                                                    [0, 2, 3, 4] if label ==
                                                    "local_accumulation" else
                                                    [0, 6, 12, 18]),
                           "index": k})
            day += 5
    rng.shuffle(events)

    # 站点基线水平与日内循环
    series = {s["db"]: {} for s in STATIONS}
    for s in STATIONS:
        level = 60.0 if s["roadside"] == 1.0 else rng.uniform(22.0, 38.0)
        for t in hours:
            weekday = t.weekday() < 5
            hour = t.hour
            diurnal = (1.0 + 0.45 * math_sin_peak(hour, weekday)) if s["roadside"] else \
                      (1.0 + 0.15 * math_sin_peak(hour, weekday))
            base = level * diurnal + rng.gauss(0.0, 3.0)
            ratio = 0.45 + rng.gauss(0.0, 0.03)
            series[s["db"]][t] = [max(5.0, base), max(8.0, base / ratio)]

    # 事件注入（乘性因子，生成机制与模型打分完全不同）
    truth = []
    for event in events:
        times = [t for t in hours
                 if t.date() == event["date"]
                 and event["start_hour"] <= t.hour < event["start_hour"] + 3]
        if not times:
            continue
        label = event["label"]
        target = STATIONS[event["index"] % 3] if label != "uncertain" else None
        for t in times:
            for s in STATIONS:
                # 事件强度按真实标注窗口的 NO2 均值标定（交通 108 / 区域 126 /
                # 积聚 120 / 不确定 74 µg/m³），使合成世界的绝对水平与真实一致
                if label == "traffic_dominant":
                    factor = 1.20 if s["db"] == target["db"] else \
                        (1.08 if s["roadside"] else 1.03)
                    ratio = 0.35
                elif label == "regional_transport":
                    factor = 2.0
                    ratio = 0.60
                elif label == "local_accumulation":
                    factor = 1.94 if s["db"] == target["db"] else 1.0
                    ratio = 0.50
                else:
                    factor = 1.19
                    ratio = 0.45 + rng.gauss(0.0, 0.03)
                no2, nox = series[s["db"]][t]
                no2 *= factor
                nox = no2 / max(ratio, 0.2)
                series[s["db"]][t] = [no2, nox]
        if len(times) == 3:
            truth.append({"label": label, "date": event["date"].isoformat(),
                          "start_hour": event["start_hour"],
                          "index": event["index"],
                          "target": target["display"] if target else "",
                          "times": [t.isoformat(sep=" ") for t in times]})
    return {"series": series, "truth": truth, "hours": hours}


def math_sin_peak(hour: int, weekday: bool) -> float:
    """工作日双峰（8/18 时）、周末平缓的日内形状（0-1）。"""
    if not weekday:
        return 0.25
    peaks = [max(0.0, 1.0 - abs(hour - p) / 3.0) for p in (8, 18)]
    return max(peaks)


def synthetic_traffic_result(rng, entry) -> dict:
    """合成交通证据（世界的一部分，对所有方法一致，带观测噪声）。"""
    base = 0.75 if entry["label"] == "traffic_dominant" else \
        (0.45 if entry["label"] == "local_accumulation" else 0.55)
    score = min(1.0, max(0.0, base + rng.gauss(0.0, 0.08)))
    return {"agent_name": "TrafficAgent", "status": "success",
            "result": {"traffic_pressure": "synthetic",
                       "traffic_pressure_score": round(score, 3),
                       "road_links": ["Synthetic Road 1"]},
            "evidence": ["合成世界交通信号。"], "confidence": 0.9,
            "data_quality": {"missing_rate": 0.0, "note": "synthetic"},
            "created_at": "synthetic", "meta": {}}


def synthetic_meteo_result(rng, entry) -> dict:
    """合成气象证据（低风/高风由事件类型决定，带噪声）。"""
    speed = (rng.uniform(0.4, 1.2) if entry["label"] in
             ("local_accumulation", "uncertain") else rng.uniform(2.0, 5.5))
    static = max(0.0, min(1.0, (2.0 - speed) / 2.0))
    return {"agent_name": "MeteorologyAgent", "status": "success",
            "result": {"weather_risk": static, "risk_type": "synthetic",
                       "dispersion_condition": "synthetic",
                       "static_wind_score": round(static, 3),
                       "wind_shift_score": round(rng.uniform(0.0, 0.3), 3),
                       "rain_removal_score": 0.5,
                       "mean_wind_speed": round(speed, 3),
                       "dominant_wind_direction": rng.uniform(0, 360),
                       "upwind_direction": "N/A", "downwind_direction": "N/A",
                       "total_precipitation": 0.0},
            "evidence": [], "confidence": 0.9,
            "data_quality": {"missing_rate": 0.0, "note": "synthetic"},
            "created_at": "synthetic", "meta": {}}


def build_db(world: dict, path: Path) -> None:
    conn = sqlite3.connect(path)
    conn.execute("""CREATE TABLE air_quality_hourly (
        id INTEGER PRIMARY KEY, station_id TEXT, station_name TEXT,
        station_type TEXT, time TEXT, aqhi REAL, no2 REAL, nox REAL,
        pm25 REAL, pm10 REAL, o3 REAL, so2 REAL, co REAL, source TEXT)""")
    rows = []
    for s in STATIONS:
        for t, (no2, nox) in world["series"][s["db"]].items():
            rows.append((None, s["db"], s["db"],
                         "roadside" if s["roadside"] else "general",
                         t.isoformat(sep=" "), None, round(no2, 2), round(nox, 2),
                         None, None, None, None, None, "synthetic"))
    conn.executemany("INSERT INTO air_quality_hourly VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
                     rows)
    conn.commit()
    conn.close()


def run_one_seed(seed: int) -> list[dict]:
    rng = random.Random(seed)
    world = build_world(rng)
    tmp = Path(tempfile.mkdtemp(prefix="zhikan_synthetic_"))
    db_path = tmp / "synthetic_air.db"
    build_db(world, db_path)
    print(f"合成世界：{N_DAYS} 天 × {len(STATIONS)} 站，事件 {len(world['truth'])} 个"
          f"（db={db_path}）", flush=True)

    # ── 管线指向合成世界（对所有方法一致）──
    # 注意：open_db 的默认参数在定义时绑定 DEFAULT_DB，必须直接替换
    # agent 命名空间里的 open_db 引用（替换模块变量无效，V9.3 修复）。
    import sqlite3 as _sq
    import tools.air_quality_tools as aqt

    target_db = Path(db_path).resolve()

    def _synthetic_open_db(_path=target_db):
        # V9.6 数据契约：任何一次连接指向别的库都立即失败，不再静默继续。
        resolved = Path(_path).resolve()
        if resolved != target_db:
            raise RuntimeError(
                f"数据契约被破坏：应连 {target_db}，实际连 {resolved}")
        conn = _sq.connect(str(resolved))
        conn.row_factory = _sq.Row
        return conn

    real_open_db = aqt.open_db
    real_default_db = aqt.DEFAULT_DB
    aqt.open_db = _synthetic_open_db
    aqt.DEFAULT_DB = target_db        # agent 显式传参 open_db(DEFAULT_DB)，
    aqt._P90_CACHE_PATH = tmp / "p90_cache.json"   # 必须同时替换模块常量

    import agents.air_quality_agent as _aqa
    _aqa.open_db = _synthetic_open_db
    _aqa.DEFAULT_DB = target_db

    from agents.air_quality_agent import AirQualityAgent
    from agents.spatial_agent import SpatialAgent
    from agents.source_agent import SourceAgent
    from agents.traffic_agent import TrafficAgent
    from agents.decison_agent import run as decision_run

    # 合成交通与气象（世界的一部分，对所有方法一致、带观测噪声）
    gen_rng = random.Random(seed + 1)
    traffic_signal = {}
    wind_signal = {}
    for entry in world["truth"]:
        key = (entry["date"], entry["start_hour"])
        base = 0.75 if entry["label"] == "traffic_dominant" else \
            (0.45 if entry["label"] == "local_accumulation" else 0.55)
        traffic_signal[key] = min(1.0, max(0.0, base + gen_rng.gauss(0.0, 0.08)))
        wind_signal[key] = (gen_rng.uniform(0.4, 1.2)
                            if entry["label"] in ("local_accumulation", "uncertain")
                            else gen_rng.uniform(2.0, 5.5))

    class SyntheticTraffic:
        name = "TrafficAgent"

        def run(self, task):
            key = (str(task.get("start_time", ""))[:10], int(str(task.get("start_time", ""))[11:13]))
            score = traffic_signal.get(key, 0.5)
            return {"agent_name": self.name, "status": "success",
                    "result": {"traffic_pressure": "synthetic",
                               "traffic_pressure_score": round(score, 3),
                               "road_links": ["Synthetic Road 1"]},
                    "evidence": ["合成世界交通信号。"], "confidence": 0.9,
                    "data_quality": {"missing_rate": 0.0, "note": "synthetic"},
                    "created_at": "synthetic", "meta": {}}

    class SyntheticMeteo:
        def __init__(self):
            self.name = "MeteorologyAgent"

        def run(self, task):
            key = (str(task.get("start_time", ""))[:10], int(str(task.get("start_time", ""))[11:13]))
            speed = wind_signal.get(key, 2.0)
            static = max(0.0, min(1.0, (2.0 - speed) / 2.0))
            return {"agent_name": self.name, "status": "success",
                    "result": {"weather_risk": static, "risk_type": "synthetic",
                               "dispersion_condition": "synthetic",
                               "static_wind_score": round(static, 3),
                               "wind_shift_score": round(gen_rng.uniform(0.0, 0.3), 3),
                               "rain_removal_score": 0.5,
                               "mean_wind_speed": round(speed, 3),
                               "dominant_wind_direction": gen_rng.uniform(0, 360),
                               "upwind_direction": "N/A",
                               "downwind_direction": "N/A",
                               "total_precipitation": 0.0},
                    "evidence": [], "confidence": 0.9,
                    "data_quality": {"missing_rate": 0.0, "note": "synthetic"},
                    "created_at": "synthetic", "meta": {}}

    air_agent = AirQualityAgent(db_path)
    traffic_agent = SyntheticTraffic()
    meteo_agent = SyntheticMeteo()
    spatial_agent = SpatialAgent()
    source_agent = SourceAgent()

    rows = []
    for entry in world["truth"]:
        station_name = entry["target"] or STATIONS[entry["index"] % 3]["display"]
        task = {"task_id": f"SYN_{entry['date']}_{entry['start_hour']}",
                "station_name": station_name,
                "start_time": entry["times"][0], "end_time": entry["times"][-1],
                "point_in_time": True}
        air = air_agent.run(dict(task))
        meteo = meteo_agent.run(dict(task))
        traffic = traffic_agent.run(dict(task))
        spatial = spatial_agent.run(dict(task), meteo)
        source = source_agent.run({"task_id": task["task_id"],
                                   "station_name": station_name},
                                  air_result=air, meteo_result=meteo,
                                  traffic_result=traffic, spatial_result=spatial)
        sres = source.get("result") or {}
        judgement = (sres.get("main_judgement") or "").lower()
        if "traffic" in judgement:
            c_label = "traffic_dominant"
        elif "regional" in judgement:
            c_label = "regional_transport"
        elif "accumulation" in judgement or "local" in judgement:
            c_label = "local_accumulation"
        else:
            c_label = "uncertain"

        # A/B 规则基线（与真实实验同构，作用于合成数据）
        times = entry["times"]
        no2s = [v for t in times for v in [world["series"][_db_of(station_name)][
            _parse(t)][0]]]
        noxs = [v for t in times for v in [world["series"][_db_of(station_name)][
            _parse(t)][1]]]
        mean_no2 = statistics.mean(no2s)
        mean_nox = statistics.mean(noxs)
        # PIT 总体：事件月之前的合成数据
        pit_rows = [(v[0], v[1]) for t, v in world["series"][_db_of(station_name)].items()
                    if t < _parse(times[0]).replace(day=1, hour=0, minute=0)
                    and t >= _parse(times[0]).replace(day=1, hour=0, minute=0)
                    - __import__("datetime").timedelta(days=365)]
        nox_pct = statistics.mean(1.0 if v < mean_nox else 0.0
                                  for v, _ in pit_rows) if pit_rows else 0.0
        no2_pct = statistics.mean(1.0 if v < mean_no2 else 0.0
                                  for v, _ in pit_rows) if pit_rows else 0.0
        a_label = ("traffic_dominant" if nox_pct >= 0.80 else
                   "local_accumulation" if no2_pct >= 0.80 else "uncertain")
        # B 多源规则（只用**可观测量**，不读真值标签）。
        # V9.5 修复：原实现 sync_norm 直接读 entry["label"]（标签泄漏）——
        # 相当于把答案喂给基线，V9.3/V9.4 的"B≫C"结论因此虚高且无效。
        # 现在区域通道改用与 C 完全同一个可观测同步证据（AirQualityAgent
        # 计算的全站 p90 超出站数），两个方法信息集相同。
        traffic_score = traffic_signal.get((entry["date"], entry["start_hour"]), 0.5)
        wind_speed = wind_signal.get((entry["date"], entry["start_hour"]), 2.0)
        sync_count = float((air.get("result") or {}).get(
            "multi_station_sync", {}).get("stations_above_p90") or 0.0)
        sync_norm = max(0.0, min(1.0, sync_count / 8.0))
        scores = {"traffic_dominant": 0.6 * nox_pct + 0.4 * traffic_score,
                  "local_accumulation": 0.6 * max(0.0, min(1.0, (2.5 - wind_speed) / 2.5))
                                        + 0.4 * no2_pct,
                  "regional_transport": 0.7 * sync_norm
                                        + 0.3 * min(1.0, wind_speed / 5.0)}
        b_label = max(scores, key=scores.get)
        if scores[b_label] < 0.55:
            b_label = "uncertain"

        rows.append({"date": entry["date"], "start_hour": entry["start_hour"],
                     "target_station": station_name, "label": entry["label"],
                     "A": a_label, "B": b_label, "C": c_label,
                     "main_judgement": sres.get("main_judgement")})

    aqt.open_db = real_open_db
    aqt.DEFAULT_DB = real_default_db
    _aqa.open_db = real_open_db
    _aqa.DEFAULT_DB = real_default_db

    return rows




def _summarise(rows: list[dict], label: str) -> dict:
    truths = [r["label"] for r in rows]
    methods = ("A", "B", "C")
    point = {m: round(macro_f1(truths, [r[m] for r in rows]), 4) for m in methods}
    recall = {m: {lab: round(sum(1 for r in rows if r["label"] == lab and r[m] == lab)
                             / max(1, sum(1 for r in rows if r["label"] == lab)), 4)
                  for lab in sorted(set(truths))} for m in methods}
    abstain = {m: round(sum(1 for r in rows if r[m] == "uncertain") / len(rows), 4)
               for m in methods}
    return {"label": label, "n": len(rows), "point_f1": point,
            "per_class_recall": recall, "abstention_rate": abstain,
            "confusion": {m: confusion(truths, [r[m] for r in rows]) for m in methods}}


def main() -> int:
    """多种子并集评估：分列单种子口径与聚合口径，避免两个数字混用。

    回应审查：此前报告把单种子 46 事件的 B/C 点估计（0.529 / 0.313）
    与 3 种子聚合的 C−B 差值（−0.413）并列，读者无法对齐。本脚本
    同时输出 per_seed（各自 46 事件）与 pooled（3 种子 138 事件）两套
    完整指标，并给出 pooled 上的按世界×日期聚类配对 CI。
    """
    seeds = SEEDS
    all_rows: list[dict] = []
    per_seed = {}
    for seed in seeds:
        rows = run_one_seed(seed)
        for r in rows:
            r["world_id"] = str(seed)
        all_rows.extend(rows)
        per_seed[str(seed)] = _summarise(rows, f"seed={seed}")
        print(f"  seed {seed}: C={per_seed[str(seed)]['point_f1']['C']} "
              f"B={per_seed[str(seed)]['point_f1']['B']}", flush=True)

    pooled = _summarise(all_rows, f"pooled({len(seeds)} seeds)")
    truths = [r["label"] for r in all_rows]
    clusters = [f"{r['world_id']}:{r['date']}" for r in all_rows]
    ci = clustered_macro_f1_diff(truths, [r["C"] for r in all_rows],
                                 [r["B"] for r in all_rows], clusters, reps=10000)

    payload = {
        "design": {
            "note": "程序生成已知来源世界：线性排放叠加 + 乘性事件因子（与模型打分机制"
                    "完全独立）；全合成空气/交通/气象，真实空间路网；系统 PIT 模式"
                    "（基线严格早于事件月）；结论限定『合成世界中的溯源一致性』",
            "seeds": list(seeds),
            "events_per_seed": len(all_rows) // len(seeds),
            "n_events_pooled": len(all_rows),
            "classes_pooled": {lab: sum(1 for r in all_rows if r["label"] == lab)
                               for lab in sorted(set(truths))},
            "independence": "生成器为线性叠加+乘性因子，不使用任何模型打分公式；"
                            "标签由生成过程直接给出，无规则标注器参与",
            "caliber_note": "per_seed 为单种子 46 事件口径；pooled 为 3 种子 138 事件"
                            "聚合口径；C−B 配对 CI 只在 pooled 上有意义（按世界×日期聚类）",
        },
        "per_seed": per_seed,
        "pooled": pooled,
        "C_minus_B_paired_ci_pooled": ci,
    }
    result_path = save_result("v9_governance_synthetic", payload)
    print(f"\nsaved -> {result_path}")
    print(f"=== pooled（{len(all_rows)} 事件）===")
    for m in ("A", "B", "C"):
        print(f"  {m}: Macro-F1={pooled['point_f1'][m]} 弃判={pooled['abstention_rate'][m]} "
              f"召回={pooled['per_class_recall'][m]}")
    print(f"  C−B pooled 配对 CI: {ci}")
    return 0


def _db_of(display: str) -> str:
    return display.replace(" Roadside", "").upper()


def _parse(s: str):
    import datetime as dt
    return dt.datetime.fromisoformat(s)


if __name__ == "__main__":
    sys.exit(main())
